/* ------------------------------------------------------------------- 守卫 */

/**
 * 命中词右侧若紧接这些字符，视为良性搭配（不判为违规）。
 *
 * 中文没有词边界，形如「你妈」这种短词会误伤「你妈妈」。守卫只在
 * **紧邻命中结尾** 处匹配，因此不会放过「你妈死了」这类真实攻击。
 */
export const BENIGN_SUFFIX: Record<string, RegExp> = {
  你妈: /^妈/,
  群交: /^流/,
  蠢猪: /^肉/,
  猪脑子: /^补/,
};

/** 命中词左侧若紧接这些字符，视为良性搭配。 */
export const BENIGN_PREFIX: Record<string, RegExp> = {
  兼职: /^不|^非/,
  加群: /^不|^别/,
  推广: /^不|^别/,
  涨粉: /^不|^别/,
  开盒: /^不|^别/,
};

function expand(words: string[], category: ModerationCategory, severity: ModerationSeverity): ModerationWord[] {
  return words.map((word) => ({ word, category, severity }));
}

