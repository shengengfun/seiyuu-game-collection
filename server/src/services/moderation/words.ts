/**
 * 本地轻量审核词库。
 *
 * 设计取舍（配合 `engine.ts` 的 Aho-Corasick 自动机）：
 * - 词条按 **类别 + 严重度** 分组，严重度决定处置方式：
 *   `3` = 命中即自动拒绝（公开侧不出现）、`2` = 转人工复核、`1` = 只计分不干预。
 * - 词库只写中文简体；繁体 / 拼音 / 谐音变体靠 `engine.ts` 的归一化与 `guard`
 *   机制兜底，不在这里堆膨胀数据。
 * - 每条词都是**子串匹配**（中文没有词边界），因此容易误伤的长词一律配 `BENIGN_SUFFIX`
 *   守卫（例如「你妈」不该拦「你妈妈也喜欢」）。
 *
 * 维护约定：
 * - 新增词只改本文件；`engine.ts` 在模块加载时构建一次自动机，之后零分配匹配。
 * - 站点是「女性声优情报站」，色情 / 开盒 / 站外导流是本板块的主要风险，优先补这三类。
 */

export type ModerationCategory = 'abuse' | 'adult' | 'politics' | 'illegal' | 'spam' | 'leak';

/** 3 = 自动拒绝，2 = 转人工复核，1 = 只计分。 */
export type ModerationSeverity = 1 | 2 | 3;

export interface ModerationWord {
  word: string;
  category: ModerationCategory;
  severity: ModerationSeverity;
}

